#!/usr/bin/env python3
"""Generate a realistic phlo-transform workspace for dogfooding.

Writes ~120 models across several transform roots and namespaces, external
sources backed by seeds, tables and incrementals (append + keyed merge),
schema contracts, unique/not-null/custom tests, multi-hop dependencies and a
`failure_lab` namespace whose models fail only when `external.fail_flag`
contains a `boom` row — so failure/resume/retry-failed flows are exercised
without changing discovery.

Usage:
    scripts/dogfood_workspace.py [OUT_DIR] [--models N]

Defaults: OUT_DIR defaults to `fixtures/dogfood`, N to 120.
"""

from __future__ import annotations

import argparse
import csv
import random
import shutil
import sys
from pathlib import Path

ROOTS = {
    "ingest": "workflows/ingest/transforms",
    "assay": "workflows/assay/transforms",
    "reporting": "workflows/reporting/transforms",
    "finance": "domains/finance/transforms",
    "failure_lab": "workflows/failure_lab/transforms",
}

PHLO_TOML = """\
# Dogfooding workspace generated by scripts/dogfood_workspace.py.
[transform]
default_schema = "analytics"
default_materialization = "view"
default_namespace = "main"

[transform.discovery]
include = [
    "workflows/*/transforms/**",
    "domains/*/transforms/**",
]

[seeds]
schema = "external"

# Contracts on the two marts every workflow converges on: the schema the
# pipeline promises downstream readers.
[model."assay.marts.daily_analyte_summary".contract]
enforced = true

[model."assay.marts.daily_analyte_summary".columns.day]
type = "DATE"
nullable = false

[model."assay.marts.daily_analyte_summary".columns.analyte]
type = "VARCHAR"
nullable = false

[model."assay.marts.daily_analyte_summary".columns.mean_concentration]
type = "DOUBLE"
nullable = true

[model."finance.marts.daily_revenue".contract]
enforced = true

[model."finance.marts.daily_revenue".columns.day]
type = "DATE"
nullable = false

[model."finance.marts.daily_revenue".columns.revenue]
type = "DOUBLE"
nullable = false
"""

